    def trash_folder(self, company_id: str, key: str, payload: object) -> dict:
        from invoice_hub.services.company_registry import CompanyRegistryError

        body = payload if isinstance(payload, dict) else {}
        if body.get("confirm") is not True:
            raise CompanyRegistryError("COMPANY_CONFIRM_REQUIRED", "请先明确确认再将文件夹移入系统回收站。", field="confirm")
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            taxpayer_before = self.registry._active_taxpayer()
            plan, kind, _entry, target = self._trash_plan(registry, company, key, body)
            if str(body.get("plan_hash") or "") != plan["plan_hash"]:
                raise CompanyRegistryError(
                    "COMPANY_PLAN_STALE", "文件夹状态已变化，请重新预览后再确认。", status_code=409, field="plan_hash"
                )
            if not plan["can_trash"]:
                raise CompanyRegistryError("COMPANY_FOLDER_TRASH_BLOCKED", plan["blocked_reason"], status_code=409)

            with self._try_profile_lock(target) as acquired:
                if not acquired:
                    raise CompanyRegistryError("COMPANY_FOLDER_BUSY", "该文件夹正在同步或读取，请稍后重试。", status_code=409)
                # Re-check live identity immediately before native recycle bin transfer.
                if directory_entry(target)[0] != "present":
                    raise CompanyRegistryError("COMPANY_PLAN_STALE", "文件夹已不存在或变化，未执行删除。", status_code=409)
                try:
                    move_to_trash(target)
                except OSError as exc:
                    raise CompanyRegistryError(
                        "COMPANY_FOLDER_TRASH_FAILED",
                        str(exc) or "未能将文件夹移入系统回收站，未执行永久删除。",
                        status_code=409,
                    ) from exc

            also_unregister = body.get("also_unregister")
            if also_unregister is None:
                also_unregister = kind == "custom"
            if kind == "custom" and bool(also_unregister):
                company["custom_folders"] = [item for item in (company.get("custom_folders") or []) if item["id"] != key]
                if not company["custom_folders"]:
                    company.pop("custom_folders", None)
            elif kind == "standard" and bool(also_unregister):
                hidden = list(company.get("hidden_subdirs") or [])
                if key not in hidden:
                    hidden.append(key)
                company["hidden_subdirs"] = hidden

            company["updated_at"] = utc_now_text()
            self.registry._save(registry)
            self.registry.repo.append_event(
                "companies.folder_trashed",
                {
                    "company_id": company_id,
                    "key": key,
                    "kind": kind,
                    "also_unregister": bool(also_unregister),
                    "revision": registry["revision"],
                },
            )
        result = self.registry._after_write(self.registry.get_company(company_id), taxpayer_before)
        result.update(trashed_key=key, trashed_path=str(target), unregistered=bool(also_unregister))
        return result

    # ---- promote in-root custom folder to its benchmark standard slot ----------------------

    def promote_folder(self, company_id: str, key: str, payload: object) -> dict:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS, CompanyRegistryError

        body = payload if isinstance(payload, dict) else {}
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            taxpayer_before = self.registry._active_taxpayer()
            self.registry._check_revision(registry, body)
            kind, entry = self._find_folder(company, key)
            if kind != "custom" or entry is None:
                raise CompanyRegistryError("COMPANY_INVALID", "该文件夹已经是默认标准槽位。", status_code=422, field="key")
            if entry["location"] != "inside_root":
                raise CompanyRegistryError(
                    "COMPANY_INVALID",
                    "只有位于公司资料夹根目录内的自定义文件夹可以切换为该公司的主标准目录；外部导入文件夹请作为独立目录使用。",
                    status_code=422,
                    field="key",
                )
            target_role = str(body.get("target_role") or entry["role"]).strip()
            if target_role not in STANDARD_SUBDIRS:
                raise CompanyRegistryError(
                    "COMPANY_INVALID",
                    "请先将功能指向设为 6 类默认目录之一，再切换为主标准目录。",
                    status_code=422,
                    field="target_role",
                )

            root = self.registry._registered_root(company["root_dir"])
            old_standard_rel = company["subdirs"][target_role]
            new_standard_rel = entry["relative_path"]
            keep_previous = bool(body.get("keep_previous_as_custom", True))
            now = utc_now_text()

            # Remove the promoted custom entry first, then switch standard mapping.
            remaining = [item for item in (company.get("custom_folders") or []) if item["id"] != key]
            company["subdirs"][target_role] = new_standard_rel
            hidden = [item for item in (company.get("hidden_subdirs") or []) if item != target_role]
            if hidden:
                company["hidden_subdirs"] = hidden
            else:
                company.pop("hidden_subdirs", None)

            preserved_id = ""
            if keep_previous and old_standard_rel.casefold() != new_standard_rel.casefold():
                if directory_entry(root)[0] == "present" and next(reversed(subdir_snapshot(root, old_standard_rel).values()))[0] == "present":
                    preserved_id = f"dir_{uuid.uuid4().hex[:12]}"
                    remaining.append({
                        "id": preserved_id,
                        "label": f"{STANDARD_SUBDIRS[target_role][0]}（原目录）",
                        "role": target_role,
                        "location": "inside_root",
                        "relative_path": old_standard_rel,
                        "external_path": "",
                        "created_at": now,
                        "updated_at": now,
                    })
            if remaining:
                company["custom_folders"] = remaining
            else:
                company.pop("custom_folders", None)
            company["updated_at"] = now
            self.registry._save(registry)
            self.registry.repo.append_event(
                "companies.folder_promoted",
                {
                    "company_id": company_id,
                    "folder_id": key,
                    "target_role": target_role,
                    "preserved_folder_id": preserved_id,
                    "revision": registry["revision"],
                },
            )
        result = self.registry._after_write(self.registry.get_company(company_id), taxpayer_before)
        result.update(promoted_to=target_role, preserved_folder_id=preserved_id)
        return result

