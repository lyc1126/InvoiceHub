def clean_folder_label(raw: object, field: str = "label") -> str:
    from invoice_hub.services.company_registry import CompanyRegistryError

    label = re.sub(r"\s+", " ", str(raw if raw is not None else "")).strip()
    if not label:
        raise CompanyRegistryError("COMPANY_INVALID", "文件夹名称不能为空。", status_code=422, field=field)
    if len(label) > MAX_FOLDER_LABEL_LENGTH:
        raise CompanyRegistryError(
            "COMPANY_INVALID",
            f"文件夹名称不能超过 {MAX_FOLDER_LABEL_LENGTH} 个字符。",
            status_code=422,
            field=field,
        )
    if any(ord(ch) < 32 for ch in label):
        raise CompanyRegistryError("COMPANY_INVALID", "文件夹名称包含非法控制字符。", status_code=422, field=field)
    return label


def clean_single_folder_name(raw: object, field: str = "new_name") -> str:
    from invoice_hub.services.company_registry import CompanyRegistryError

    name = str(raw if raw is not None else "").strip()
    if not name or name in {".", ".."} or "/" in name or "\\" in name:
        raise CompanyRegistryError("COMPANY_INVALID", "新文件夹名必须是单层目录名，不能包含路径分隔符。", status_code=422, field=field)
    if any(ch in _WINDOWS_RESERVED_CHARS or ord(ch) < 32 for ch in name):
        raise CompanyRegistryError("COMPANY_INVALID", "文件夹名包含不允许的字符。", status_code=422, field=field)
    if name.endswith(".") or _WINDOWS_RESERVED_NAMES.fullmatch(name.split(".")[0]):
        raise CompanyRegistryError("COMPANY_INVALID", "文件夹名不能使用系统保留名或以句点结尾。", status_code=422, field=field)
    return name


def clean_folder_role(raw: object, field: str = "role") -> str:
    from invoice_hub.services.company_registry import CompanyRegistryError

    role = str(raw if raw is not None else "").strip() or "general"
    if role not in FOLDER_ROLES:
        raise CompanyRegistryError("COMPANY_INVALID", f"不支持的功能指向：{role}", status_code=422, field=field)
    return role


def _is_forbidden_system_root(path: Path, project_root: Path) -> bool:
    try:
        resolved = path.resolve()
    except OSError:
        return True
    if resolved == resolved.parent:
        return True
    try:
        if resolved == Path.home().resolve():
            return True
    except (OSError, RuntimeError):
        pass
    try:
        if resolved == project_root.resolve():
            return True
    except OSError:
        pass
    return False


def _paths_overlap(a: Path, b: Path) -> bool:
    return _is_within(a, b) or _is_within(b, a)


def _count_folder_contents(target: Path, limit: int = TRASH_SCAN_LIMIT) -> tuple[int, int, int, bool]:
    """Bounded read-only scan of files/subdirs inside ``target`` for trash preview confirmation."""
    file_count = 0
    dir_count = 0
    total_bytes = 0
    truncated = False
    pending = [target]
    while pending:
        current = pending.pop()
        try:
            with os.scandir(current) as entries:
                for entry in entries:
                    try:
                        if entry.is_symlink():
                            file_count += 1
                        elif entry.is_dir(follow_symlinks=False):
                            dir_count += 1
                            pending.append(Path(entry.path))
                        else:
                            file_count += 1
                            total_bytes += int(entry.stat(follow_symlinks=False).st_size)
                    except OSError:
                        file_count += 1
                    if file_count + dir_count >= limit:
                        truncated = True
                        return file_count, dir_count, total_bytes, truncated
        except OSError:
            continue
    return file_count, dir_count, total_bytes, truncated


class CompanyFolderService:
    """Manage custom and standard subfolders under a registered company."""

    def __init__(self, registry: "CompanyRegistryService") -> None:
        self.registry = registry

    def _try_profile_lock(self, target: Path):
        profile = target_profile_for(self.registry.config, target)
        # Never materialize runtime/targets/<id> for a folder that has never been synced.
        if not Path(profile.state_dir).is_dir():
            return nullcontext(True)
        return MonitorState(profile).try_sync_write_lock()

    def _entry_path(self, company: dict, entry: dict) -> Path:
        root = self.registry._registered_root(company["root_dir"])
        if entry["location"] == "inside_root":
            return root / entry["relative_path"]
        return resolve_external_folder(self.registry.config.root_dir, entry["external_path"])

    def _all_company_folder_paths(
        self,
        company: dict,
        *,
        exclude_key: str | None = None,
    ) -> list[tuple[str, str, Path]]:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS

        root = self.registry._registered_root(company["root_dir"])
        items: list[tuple[str, str, Path]] = []
        for key, (default_label, _hints) in STANDARD_SUBDIRS.items():
            if key == exclude_key:
                continue
            label = (company.get("subdir_labels") or {}).get(key) or default_label
            items.append((key, label, root / company["subdirs"][key]))
        for entry in company.get("custom_folders") or []:
            if entry["id"] == exclude_key:
                continue
            items.append((entry["id"], entry["label"], self._entry_path(company, entry)))
        return items

    def _check_no_overlap(
        self,
        registry: dict,
        company: dict,
        candidate: Path,
        *,
        location: str,
        field: str,
        exclude_key: str | None = None,
    ) -> None:
        from invoice_hub.services.company_registry import CompanyRegistryError

        company_root = self.registry._registered_root(company["root_dir"])
        if location == "external" and _paths_overlap(candidate, company_root):
            raise CompanyRegistryError(
                "COMPANY_INVALID",
                "外部导入文件夹不能与本公司资料夹根目录相同或互相包含。",
                status_code=422,
                field=field,
            )
        for _other_key, other_label, other_path in self._all_company_folder_paths(company, exclude_key=exclude_key):
            if _paths_overlap(candidate, other_path):
                raise CompanyRegistryError(
                    "COMPANY_INVALID",
                    f"该路径与本公司已登记的“{other_label}”相同或互相包含。",
                    status_code=422,
                    field=field,
                )
        for other_company in registry["companies"]:
            if other_company["id"] == company["id"]:
                continue
            other_root = self.registry._registered_root(other_company["root_dir"])
            if _paths_overlap(candidate, other_root):
                raise CompanyRegistryError(
                    "COMPANY_INVALID",
                    f"该路径与已登记公司“{other_company['name']}”的资料夹重叠。",
                    status_code=422,
                    field=field,
                )
            for ext in other_company.get("custom_folders") or []:
                if ext["location"] != "external":
                    continue
                ext_path = resolve_external_folder(self.registry.config.root_dir, ext["external_path"])
                if _paths_overlap(candidate, ext_path):
                    raise CompanyRegistryError(
                        "COMPANY_INVALID",
                        f"该路径与已登记公司“{other_company['name']}”的外部文件夹“{ext['label']}”重叠。",
                        status_code=422,
                        field=field,
                    )

    def _check_not_monitored(self, target: Path, action_label: str) -> None:
        from invoice_hub.services.company_registry import CompanyRegistryError

        watch_dir = Path(self.registry.active_profile.watch_dir)
        if _paths_overlap(target, watch_dir):
            raise CompanyRegistryError(
                "COMPANY_FOLDER_MONITORED",
                f"该文件夹与当前监控目录重叠，请先切换监控目录后再{action_label}。",
                status_code=409,
            )

    def _find_folder(self, company: dict, key: str) -> tuple[str, dict | None]:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS, CompanyRegistryError

        if key in STANDARD_SUBDIRS:
            return "standard", None
        for entry in company.get("custom_folders") or []:
            if entry["id"] == key:
                return "custom", entry
        raise CompanyRegistryError("COMPANY_DIRECTORY_NOT_FOUND", "公司清单里没有这个文件夹。", status_code=404, field="key")

    @staticmethod
    def _suggest_role(name: str) -> str:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS

        folded = re.sub(r"\s+", "", name.casefold())
        hits = [
            key
            for key, (_standard, hints) in STANDARD_SUBDIRS.items()
            if any(hint.casefold() in folded for hint in hints)
        ]
        return hits[0] if len(hits) == 1 else "general"

    # ---- discover unmapped in-root directories + hidden defaults ---------------------------

    def discover(self, company_id: str) -> dict:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS

        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            root = self.registry._registered_root(company["root_dir"])
            root_status = directory_entry(root)[0]
            existing_paths = [path for _k, _lbl, path in self._all_company_folder_paths(company)]
            hidden_keys = set(company.get("hidden_subdirs") or [])
            subdir_labels = company.get("subdir_labels") or {}
            hidden_standard = []
            for key, (default_label, _hints) in STANDARD_SUBDIRS.items():
                if key not in hidden_keys:
                    continue
                relative = company["subdirs"][key]
                path, status = (
                    self.registry._subdir_status(root, relative)
                    if root_status == "present"
                    else (root / relative, "root_unavailable")
                )
                hidden_standard.append({
                    "key": key,
                    "label": subdir_labels.get(key) or default_label,
                    "default_label": default_label,
                    "relative_path": relative,
                    "path": str(path),
                    "status": status,
                })
            revision = registry["revision"]

        candidates: list[dict[str, str]] = []
        if root_status == "present":
            try:
                children = sorted(root.iterdir(), key=lambda item: item.name.casefold())
            except OSError:
                children = []
            for child in children:
                if child.name.startswith(".") or child.name in _DISCOVERY_SKIP_NAMES:
                    continue
                if directory_entry(child)[0] != "present":
                    continue
                if any(_paths_overlap(child, registered) for registered in existing_paths):
                    continue
                role = self._suggest_role(child.name)
                candidates.append({
                    "relative_path": child.name,
                    "label": child.name,
                    "path": str(child),
                    "suggested_role": role,
                    "suggested_role_label": FOLDER_ROLES[role]["label"],
                })
        return {
            "ok": True,
            "company_id": company_id,
            "revision": revision,
            "root_status": root_status,
            "candidates": candidates,
            "hidden_standard_subdirs": hidden_standard,
            "roles": folder_roles_payload(),
        }

    # ---- create new custom folder inside company root (preview -> confirm) -----------------

    def _create_plan(self, registry: dict, company: dict, payload: dict) -> tuple[dict, str, str, str, dict]:
        from invoice_hub.services.company_registry import CompanyRegistryError, clean_relative_subdir

        self.registry._check_revision(registry, payload)
        if len(company.get("custom_folders") or []) >= MAX_CUSTOM_FOLDERS:
            raise CompanyRegistryError("COMPANY_INVALID", f"每家公司最多添加 {MAX_CUSTOM_FOLDERS} 个自定义文件夹。", field="label")
        label = clean_folder_label(payload.get("label"), "label")
        raw_rel = payload.get("relative_path")
        relative = clean_relative_subdir(label if raw_rel is None or not str(raw_rel).strip() else raw_rel, "relative_path")
        role = clean_folder_role(payload.get("role"), "role")

        root = self.registry._registered_root(company["root_dir"])
        snapshots = subdir_snapshot(root, relative)
        target = root / relative
        self._check_no_overlap(registry, company, target, location="inside_root", field="relative_path")

        if snapshots["."][0] != "present":
            action, reason = "blocked", "公司资料夹不存在或不是文件夹。"
        else:
            status = next(reversed(snapshots.values()))[0]
            if status == "missing":
                action, reason = "create", ""
            elif status == "present":
                action, reason = "blocked", "该文件夹已存在，请改用「导入已有文件夹」。"
            elif status == "not_directory":
                action, reason = "blocked", "路径上已有同名文件，不会改动它；请换一个名称。"
            elif status == "outside_root":
                action, reason = "blocked", "路径包含链接或越出公司资料夹，不会创建。"
            else:
                action, reason = "blocked", "无法读取该路径。"

        binding = {
            "op": "create_custom_folder",
            "company_id": company["id"],
            "registry_revision": registry["revision"],
            "root": str(root).casefold(),
            "relative_path": relative.casefold(),
            "label": label,
            "role": role,
            "directory_identities": snapshots,
        }
        plan_hash = hashlib.sha256(json.dumps(binding, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()
        plan = {
            "ok": True,
            "company_id": company["id"],
            "revision": registry["revision"],
            "label": label,
            "relative_path": relative,
            "path": str(target),
            "role": role,
            "role_label": FOLDER_ROLES[role]["label"],
            "action": action,
            "reason": reason,
            "plan_hash": plan_hash,
        }
        return plan, label, relative, role, snapshots

    def preview_create(self, company_id: str, payload: object) -> dict:
        body = payload if isinstance(payload, dict) else {}
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            plan, *_ = self._create_plan(registry, company, body)
            return plan

    def create(self, company_id: str, payload: object) -> dict:
        from invoice_hub.services.company_registry import CompanyRegistryError

        body = payload if isinstance(payload, dict) else {}
        if body.get("confirm") is not True:
            raise CompanyRegistryError("COMPANY_CONFIRM_REQUIRED", "请先确认要创建的文件夹。", field="confirm")
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            plan, label, relative, role, snapshots = self._create_plan(registry, company, body)
            if str(body.get("plan_hash") or "") != plan["plan_hash"]:
                raise CompanyRegistryError(
                    "COMPANY_PLAN_STALE", "目录状态已变化，请重新预览后确认。", status_code=409, field="plan_hash"
                )
            if plan["action"] != "create":
                raise CompanyRegistryError("COMPANY_INVALID", plan["reason"] or "该路径无法创建文件夹。", status_code=422, field="relative_path")
            root = self.registry._registered_root(company["root_dir"])
            try:
                create_empty_subdir(root, relative, dict(snapshots))
            except FileExistsError as exc:
                raise CompanyRegistryError("COMPANY_PLAN_STALE", "路径上刚出现同名目录或文件，请重新预览。", status_code=409) from exc
            except CompanyDirectoryChanged as exc:
                raise CompanyRegistryError("COMPANY_PLAN_STALE", str(exc), status_code=409) from exc
            except OSError as exc:
                raise CompanyRegistryError("COMPANY_FOLDER_IO_ERROR", f"创建文件夹失败：{exc.strerror or exc}", status_code=409) from exc

            now = utc_now_text()
            entry = {
                "id": f"dir_{uuid.uuid4().hex[:12]}",
                "label": label,
                "role": role,
                "location": "inside_root",
                "relative_path": relative,
                "external_path": "",
                "created_at": now,
                "updated_at": now,
            }
            company.setdefault("custom_folders", []).append(entry)
            company["updated_at"] = now
            self.registry._save(registry)
            self.registry.repo.append_event(
                "companies.folder_created",
                {"company_id": company_id, "folder_id": entry["id"], "role": role, "revision": registry["revision"]},
            )
            folder_id = entry["id"]
        result = self.registry.get_company(company_id)
        result["folder_id"] = folder_id
        return result

    # ---- import existing folder (in-root or external) --------------------------------------

    def import_folder(self, company_id: str, payload: object) -> dict:
        from invoice_hub.services.company_registry import CompanyRegistryError, clean_relative_subdir

        body = payload if isinstance(payload, dict) else {}
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            taxpayer_before = self.registry._active_taxpayer()
            self.registry._check_revision(registry, body)
            if len(company.get("custom_folders") or []) >= MAX_CUSTOM_FOLDERS:
                raise CompanyRegistryError("COMPANY_INVALID", f"每家公司最多添加 {MAX_CUSTOM_FOLDERS} 个自定义文件夹。", field="path")

            role = clean_folder_role(body.get("role"), "role")
            raw_relative = str(body.get("relative_path") or "").strip()
            raw_path = str(body.get("path") or "").strip().strip('"').strip("'")
            root = self.registry._registered_root(company["root_dir"])
            project_root = self.registry.config.root_dir

            if raw_relative and not raw_path:
                relative = clean_relative_subdir(raw_relative, "relative_path")
                snapshots = subdir_snapshot(root, relative)
                if snapshots["."][0] != "present":
                    raise CompanyRegistryError("COMPANY_INVALID", "公司资料夹不存在或不可用。", status_code=422, field="relative_path")
                status = next(reversed(snapshots.values()))[0]
                if status != "present":
                    raise CompanyRegistryError("COMPANY_INVALID", "指定的子文件夹不存在、是链接或不是文件夹。", status_code=422, field="relative_path")
                target = root / relative
                location = "inside_root"
                external_stored = ""
                default_label = Path(relative).name
            else:
                if not raw_path or "\0" in raw_path:
                    raise CompanyRegistryError("COMPANY_INVALID", "请选择或填写要导入的文件夹路径。", status_code=422, field="path")
                candidate = Path(raw_path).expanduser()
                if not candidate.is_absolute():
                    candidate = root / candidate
                entry_status = directory_entry(candidate)[0]
                if entry_status != "present":
                    raise CompanyRegistryError(
                        "COMPANY_INVALID",
                        "所选路径不存在、是链接或不是普通文件夹，不能导入。",
                        status_code=422,
                        field="path",
                    )
                resolved = candidate.resolve()
                if _is_forbidden_system_root(resolved, project_root):
                    raise CompanyRegistryError("COMPANY_INVALID", "不能导入磁盘根目录、用户主目录或程序根目录。", status_code=422, field="path")

                root_present = directory_entry(root)[0] == "present"
                if root_present and _is_within(resolved, root.resolve()):
                    if resolved == root.resolve():
                        raise CompanyRegistryError("COMPANY_INVALID", "不能直接导入公司资料夹根目录本身。", status_code=422, field="path")
                    rel_text = resolved.relative_to(root.resolve()).as_posix()
                    relative = clean_relative_subdir(rel_text, "path")
                    snapshots = subdir_snapshot(root, relative)
                    if next(reversed(snapshots.values()))[0] != "present":
                        raise CompanyRegistryError("COMPANY_INVALID", "路径包含链接或越出公司资料夹，不能导入。", status_code=422, field="path")
                    target = root / relative
                    location = "inside_root"
                    external_stored = ""
                    default_label = Path(relative).name
                else:
                    # External directory mounted outside the company root.
                    location = "external"
                    relative = ""
                    target = resolved
                    external_stored = serialize_config_path(project_root, resolved)
                    default_label = resolved.name or str(resolved)

            self._check_no_overlap(
                registry,
                company,
                target,
                location=location,
                field="path" if raw_path else "relative_path",
            )
            label = clean_folder_label(body.get("label") or default_label, "label")
            now = utc_now_text()
            entry = {
                "id": f"dir_{uuid.uuid4().hex[:12]}",
                "label": label,
                "role": role,
                "location": location,
                "relative_path": relative,
                "external_path": external_stored,
                "created_at": now,
                "updated_at": now,
            }
            company.setdefault("custom_folders", []).append(entry)
            company["updated_at"] = now
            self.registry._save(registry)
            self.registry.repo.append_event(
                "companies.folder_imported",
                {"company_id": company_id, "folder_id": entry["id"], "location": location, "role": role, "revision": registry["revision"]},
            )
            folder_id = entry["id"]
        result = self.registry._after_write(self.registry.get_company(company_id), taxpayer_before)
        result["folder_id"] = folder_id
        return result

    # ---- update / rename (display label, role, and optional atomic disk rename) ------------

    def update_folder(self, company_id: str, key: str, payload: object) -> dict:
        from invoice_hub.services.company_registry import STANDARD_SUBDIRS, CompanyRegistryError, clean_relative_subdir

        body = payload if isinstance(payload, dict) else {}
        with self.registry._lock:
            registry = self.registry._load()
            company = self.registry._find(registry, company_id)
            taxpayer_before = self.registry._active_taxpayer()
            self.registry._check_revision(registry, body)
            kind, entry = self._find_folder(company, key)
            root = self.registry._registered_root(company["root_dir"])
            project_root = self.registry.config.root_dir
            rename_disk = bool(body.get("rename_disk", False))
            disk_renamed = False

            if kind == "standard":
                default_label = STANDARD_SUBDIRS[key][0]
                old_relative = company["subdirs"][key]
                old_path = root / old_relative
                new_label = clean_folder_label(body["label"], "label") if "label" in body else ((company.get("subdir_labels") or {}).get(key) or default_label)
                new_relative = old_relative
                if rename_disk:
                    raw_target = body.get("new_relative_path")
                    if raw_target is None or not str(raw_target).strip():
                        raw_target = body.get("new_name") or new_label
                    new_relative = clean_relative_subdir(raw_target, "new_relative_path")
                    if new_relative != old_relative:
                        if directory_entry(root)[0] != "present" or next(reversed(subdir_snapshot(root, old_relative).values()))[0] != "present":
                            raise CompanyRegistryError("COMPANY_DIRECTORY_MISSING", "原文件夹不存在或不可用，无法在硬盘上重命名。", status_code=409)
                        self._check_not_monitored(old_path, "重命名文件夹")
                        new_path = root / new_relative
                        self._check_no_overlap(registry, company, new_path, location="inside_root", field="new_relative_path", exclude_key=key)
                        target_snap = subdir_snapshot(root, new_relative)
                        if next(reversed(target_snap.values()))[0] != "missing":
                            raise CompanyRegistryError("COMPANY_INVALID", "目标路径已存在文件或文件夹，不能覆盖。", status_code=409, field="new_relative_path")
                        # Same-parent or existing parent directory inside company root only.
                        parent_rel = Path(new_relative).parent.as_posix()
                        if parent_rel not in {"", "."} and target_snap.get(parent_rel, [None])[0] != "present":
                            raise CompanyRegistryError("COMPANY_INVALID", "目标上级目录不存在，请只在同一目录内改名。", status_code=422, field="new_relative_path")
                        with self._try_profile_lock(old_path) as acquired:
                            if not acquired:
                                raise CompanyRegistryError("COMPANY_FOLDER_BUSY", "该文件夹正在同步或读取，请稍后重试。", status_code=409)
                            try:
                                os.rename(old_path, new_path)
                            except OSError as exc:
                                raise CompanyRegistryError("COMPANY_FOLDER_IO_ERROR", f"重命名文件夹失败：{exc.strerror or exc}", status_code=409) from exc
                        disk_renamed = True
                        company["subdirs"][key] = new_relative

                labels = dict(company.get("subdir_labels") or {})
                if new_label == default_label:
                    labels.pop(key, None)
                else:
                    labels[key] = new_label
                if labels:
                    company["subdir_labels"] = labels
                else:
                    company.pop("subdir_labels", None)
                company["updated_at"] = utc_now_text()
                try:
                    self.registry._save(registry)
                except Exception:
                    if disk_renamed:
                        try:
                            os.rename(root / new_relative, old_path)
                        except OSError:
                            pass
                    raise
            else:
                assert entry is not None
                old_path = self._entry_path(company, entry)
                new_label = clean_folder_label(body["label"], "label") if "label" in body else entry["label"]
                new_role = clean_folder_role(body["role"], "role") if "role" in body else entry["role"]
                new_relative = entry["relative_path"]
                new_external = entry["external_path"]
                new_path = old_path

                if rename_disk:
                    if directory_entry(old_path)[0] != "present":
                        raise CompanyRegistryError("COMPANY_DIRECTORY_MISSING", "原文件夹不存在或不可用，无法在硬盘上重命名。", status_code=409)
                    if _is_forbidden_system_root(old_path, project_root):
                        raise CompanyRegistryError("COMPANY_INVALID", "不能重命名系统或根目录。", status_code=422)
                    self._check_not_monitored(old_path, "重命名文件夹")

                    if entry["location"] == "inside_root":
                        raw_target = body.get("new_relative_path")
                        if raw_target is None or not str(raw_target).strip():
                            raw_target = body.get("new_name") or new_label
                        new_relative = clean_relative_subdir(raw_target, "new_relative_path")
                        if new_relative != entry["relative_path"]:
                            new_path = root / new_relative
                            self._check_no_overlap(registry, company, new_path, location="inside_root", field="new_relative_path", exclude_key=key)
                            target_snap = subdir_snapshot(root, new_relative)
                            if next(reversed(target_snap.values()))[0] != "missing":
                                raise CompanyRegistryError("COMPANY_INVALID", "目标路径已存在文件或文件夹，不能覆盖。", status_code=409, field="new_relative_path")
                            parent_rel = Path(new_relative).parent.as_posix()
                            if parent_rel not in {"", "."} and target_snap.get(parent_rel, [None])[0] != "present":
                                raise CompanyRegistryError("COMPANY_INVALID", "目标上级目录不存在，请只在同一目录内改名。", status_code=422, field="new_relative_path")
                    else:
                        new_name = clean_single_folder_name(body.get("new_name") or new_label, "new_name")
                        if new_name != old_path.name:
                            new_path = old_path.parent / new_name
                            if _is_forbidden_system_root(new_path, project_root):
                                raise CompanyRegistryError("COMPANY_INVALID", "目标路径受系统保护，不能重命名。", status_code=422, field="new_name")
                            self._check_no_overlap(registry, company, new_path, location="external", field="new_name", exclude_key=key)
                            if directory_entry(new_path)[0] != "missing":
                                raise CompanyRegistryError("COMPANY_INVALID", "同目录下已存在同名文件或文件夹，不能覆盖。", status_code=409, field="new_name")
                            new_external = serialize_config_path(project_root, new_path)

                    if new_path != old_path:
                        with self._try_profile_lock(old_path) as acquired:
                            if not acquired:
                                raise CompanyRegistryError("COMPANY_FOLDER_BUSY", "该文件夹正在同步或读取，请稍后重试。", status_code=409)
                            try:
                                os.rename(old_path, new_path)
                            except OSError as exc:
                                raise CompanyRegistryError("COMPANY_FOLDER_IO_ERROR", f"重命名文件夹失败：{exc.strerror or exc}", status_code=409) from exc
                        disk_renamed = True

                now = utc_now_text()
                entry["label"] = new_label
                entry["role"] = new_role
                entry["relative_path"] = new_relative
                entry["external_path"] = new_external
                entry["updated_at"] = now
                company["updated_at"] = now
                try:
                    self.registry._save(registry)
                except Exception:
                    if disk_renamed:
                        try:
                            os.rename(new_path, old_path)
                        except OSError:
                            pass
                    raise

            self.registry.repo.append_event(
                "companies.folder_updated",
                {"company_id": company_id, "key": key, "disk_renamed": disk_renamed, "revision": registry["revision"]},
            )
        result = self.registry._after_write(self.registry.get_company(company_id), taxpayer_before)
        result["disk_renamed"] = disk_renamed
        return result

