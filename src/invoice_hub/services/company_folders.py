"""Per-company custom & standard folder management: create, import, rename, hide/remove, trash, promote.

All mutations flow through CompanyRegistryService's shared RLock and optimistic revision (CAS),
preserving single-active watch_dir isolation:
- Creating an empty folder uses preview (plan_hash + directory identity) -> confirm -> create_empty_subdir.
- Importing an existing folder accepts either a subfolder inside the company root or an external local
  directory outside the company root, never moving or altering files on disk, while forbidding links,
  filesystem roots, and cross-company/intra-company path overlaps.
- Deleting a folder separates non-destructive unregister/hide (zero disk changes) from native recycle-bin
  removal (preview -> plan_hash + directory identity + confirm -> move_to_trash, never permanent delete).
- Custom folders carry a benchmark functional role (the 6 standard roles or ``general``) so single-folder
  views/refresh/period-check/bank-layouts/same-number work out of the box without polluting company-wide
  ledgers or vouchers until explicitly promoted to a standard slot.
"""

